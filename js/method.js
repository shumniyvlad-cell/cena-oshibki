  function num(v) { const n = Number(String(v || '').replace(/[^\d]/g, '')); return isFinite(n) ? n : 0; }

  function compute(a) {
    const spend = Math.max(num(a.spend), 1);
    const cushion = num(a.cushion);
    const stake = num(a.stake);
    const income = num(a.income);
    const income6 = num(a.income6);
    const backTime = Number(a.back_time) || 5;
    const left = Math.max(cushion - stake, 0);
    const gap = Math.max(spend - income6, 0); // сколько не хватает в месяц после решения
    const runway = gap > 0 ? left / gap : 99;
    const lostIncome = Math.max(income - income6, 0) * backTime;
    const price = stake + lostIncome; // цена ошибки: ставка + недополученный доход за время отката
    const safeCushion = spend * 6 + stake;

    const z = []; // [ключ, вес]
    if (runway < 3) z.push(['runway', 26]); else if (runway < 6) z.push(['runway', 15]); else if (runway < 12) z.push(['runway', 5]);
    if (a.back === 'no') z.push(['burn', 20]); else if (a.back === 'worse') z.push(['burn', 9]);
    if (a.deps === 'all') z.push(['deps', 10]); else if (a.deps === 'some') z.push(['deps', 5]);
    if (Number(a.talked) === 0) z.push(['nodata', 12]); else if (Number(a.talked) === 1) z.push(['nodata', 5]);
    if (a.proof === 'no') z.push(['noproof', 10]); else if (a.proof === 'deal') z.push(['noproof', 4]);
    if (a.small === 'no') z.push(['allin', 12]); else if (a.small === 'part') z.push(['allin', 5]);
    if (a.dir === 'from') z.push(['escape', 8]); else if (a.dir === 'both') z.push(['escape', 3]);
    if (a.event === 'yes') z.push(['hot', 8]);
    if (a.push === 'trend' || a.push === 'people') z.push(['pressure', 6]);
    if (a.think === 'long') z.push(['stuck', 4]);
    const burnList = Array.isArray(a.burn) ? a.burn.filter((x) => x !== 'nothing') : [];
    let force = z.reduce((s, x) => s + x[1], 0) + Math.min(burnList.length * 2, 6);
    if (a.before === 'fail') force += 3; if (a.before === 'win') force -= 4;
    if (a.sleep === 'fear') force += 3;
    force = Math.max(3, Math.min(100, Math.round(force)));

    let verdict = force >= 60 ? 'red' : force >= 32 ? 'yellow' : 'green';
    if (a.back === 'no' && runway < 3) verdict = 'red';

    const zones = z.sort((x, y) => y[1] - x[1]).slice(0, 3).map((x) => x[0]);
    if (zones.length === 0) zones.push('stuck');

    const decideOn = new Date(); decideOn.setDate(decideOn.getDate() + 21);
    return { answers: a, spend, cushion, stake, income, income6, backTime, left, runway, price, lostIncome, safeCushion, force, verdict, zones, decideOn, type: a.type || 'quit' };
  }

